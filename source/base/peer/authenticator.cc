namespace {

constexpr Minutes kTimeout{ 1 };

constexpr size_t kMaxOsNameLength = 64;
constexpr size_t kMaxComputerNameLength = 64;
constexpr size_t kMaxArchLength = 32;
constexpr size_t kMaxDisplayNameLength = 64;
constexpr quint32 kMaxVersionComponent = 999;

volatile auto g_errorCodeType = qRegisterMetaType<Authenticator::ErrorCode>();

//--------------------------------------------------------------------------------------------------
// Control, format and other non-printable characters are rejected: they are able to break or spoof
// the output in the user interface and in the logs.
bool isPrintableChar(char32_t text_char)
{
    return QChar::isPrint(text_char);
}

//--------------------------------------------------------------------------------------------------
// The computer name is the host name of the machine, but on mobile platforms the model of the
// device is used instead, so the separators of both are allowed. Windows allows non-latin computer
// names, that is why letters and digits of any alphabet are accepted.
bool isValidComputerNameChar(char32_t name_char)
{
    if (QChar::isLetterOrNumber(name_char))
        return true;

    if (name_char == '.' ||
        name_char == '-' ||
        name_char == '_' ||
        name_char == '+' ||
        name_char == '(' ||
        name_char == ')' ||
        name_char == ' ')
    {
        return true;
    }

    return false;
}

//--------------------------------------------------------------------------------------------------
// The architecture name is never entered by the user: it is generated by the code and always
// consists of latin letters, digits and separators.
bool isValidArchChar(char32_t arch_char)
{
    if (arch_char >= 'a' && arch_char <= 'z')
        return true;

    if (arch_char >= 'A' && arch_char <= 'Z')
        return true;

    if (arch_char >= '0' && arch_char <= '9')
        return true;

    if (arch_char == '.' ||
        arch_char == '_' ||
        arch_char == '-')
    {
        return true;
    }

    return false;
}

//--------------------------------------------------------------------------------------------------
// Checks the text received from the peer: it must not be longer than |max_length| bytes, must be
// valid UTF-8 and each of its characters must be accepted by |is_valid_char|. Empty text is
// considered valid here: the callers check it themselves, because some fields are optional.
bool isValidText(std::string_view text, size_t max_length, bool (*is_valid_char)(char32_t))
{
    if (text.size() > max_length)
        return false;

    QByteArrayView bytes(text.data(), static_cast<qsizetype>(text.size()));
    if (!bytes.isValidUtf8())
        return false;

    const QList<uint> characters = QString::fromUtf8(bytes).toUcs4();
    for (uint character : std::as_const(characters))
    {
        if (!is_valid_char(static_cast<char32_t>(character)))
            return false;
    }

    return true;
}

} // namespace

//--------------------------------------------------------------------------------------------------
Authenticator::Authenticator(Protocol protocol, QObject* parent)
    : QObject(parent),
      encryption_(proto::key_exchange::ENCRYPTION_UNKNOWN),
      identify_(proto::key_exchange::IDENTIFY_SRP),
      transcript_hash_(protocol == Protocol::NG ? GenericHash::SHA256 : GenericHash::BLAKE2s256),
      timer_(new QTimer(this))
{
    CLOG(TRACE) << "Ctor";

    timer_->setSingleShot(true);
    connect(timer_, &QTimer::timeout, this, [this]()
    {
        finish(FROM_HERE, ErrorCode::UNKNOWN_ERROR);
    });
}

//--------------------------------------------------------------------------------------------------
Authenticator::~Authenticator()
{
    CLOG(TRACE) << "Dtor";
}

//--------------------------------------------------------------------------------------------------
void Authenticator::start()
{
    if (state() != State::STOPPED)
    {
        CLOG(ERROR) << "Trying to start an already running authenticator";
        return;
    }

    state_ = State::PENDING;

    // If authentication does not complete within the specified time interval, an error will be
    // raised.
    timer_->start(kTimeout);

    if (onStarted())
        CLOG(TRACE) << "Authentication started";
    else
        CLOG(ERROR) << "Unable to start authentication";
}

//--------------------------------------------------------------------------------------------------
SecureByteArray Authenticator::sessionKey(Direction direction) const
{
    if (!key_ready_)
        return SecureByteArray();

    QByteArray label = keyLabel(direction);
    if (label.isEmpty())
        return SecureByteArray(transcript_hash_.result());

    GenericHash hash(transcript_hash_.type());
    hash.addData(transcript_hash_.result());
    hash.addData(label);

    return SecureByteArray(hash.result());
}

//--------------------------------------------------------------------------------------------------
const QByteArray& Authenticator::iv(Direction direction) const
{
    return direction == Direction::ENCRYPT ? encrypt_iv_ : decrypt_iv_;
}

//--------------------------------------------------------------------------------------------------
void Authenticator::onIncomingMessage(const QByteArray& data)
{
    if (state() != State::PENDING)
        return;
    onReceived(data);
}

//--------------------------------------------------------------------------------------------------
void Authenticator::appendTranscript(const QByteArray& data)
{
    transcript_hash_.addData(data);
}

//--------------------------------------------------------------------------------------------------
void Authenticator::setSessionKeyReady()
{
    key_ready_ = true;
    emit sig_keyChanged();
}

//--------------------------------------------------------------------------------------------------
void Authenticator::finish(const Location& location, ErrorCode error_code)
{
    timer_->stop();

    if (error_code == ErrorCode::SUCCESS)
        state_ = State::SUCCESS;
    else
        state_ = State::FAILED;

    CLOG(TRACE) << "Authenticator finished:" << error_code << "(" << location << ")";
    emit sig_finished(error_code);
}

//--------------------------------------------------------------------------------------------------
bool Authenticator::setPeerVersion(const proto::peer::Version& version)
{
    if (version.major() > kMaxVersionComponent || version.minor() > kMaxVersionComponent ||
        version.patch() > kMaxVersionComponent)
    {
        CLOG(ERROR) << "Invalid peer version:" << version.major() << version.minor()
                    << version.patch();
        return false;
    }

    QVersionNumber peer_version = parse(version);
    if (peer_version.normalized().isNull())
    {
        CLOG(ERROR) << "Empty peer version";
        return false;
    }

    CLOG(TRACE) << "Version changed from" << peer_version_ << "to" << peer_version;
    peer_version_ = peer_version;
    return true;
}

//--------------------------------------------------------------------------------------------------
bool Authenticator::setPeerOsName(std::string_view name)
{
    if (strTrimmed(name).empty() || !isValidText(name, kMaxOsNameLength, isPrintableChar))
    {
        CLOG(ERROR) << "Invalid peer OS name (size:" << name.size() << ")";
        return false;
    }

    peer_os_name_ = name;
    return true;
}

//--------------------------------------------------------------------------------------------------
bool Authenticator::setPeerComputerName(std::string_view name)
{
    if (strTrimmed(name).empty() || !isValidText(name, kMaxComputerNameLength, isValidComputerNameChar))
    {
        CLOG(ERROR) << "Invalid peer computer name (size:" << name.size() << ")";
        return false;
    }

    peer_computer_name_ = name;
    return true;
}

//--------------------------------------------------------------------------------------------------
bool Authenticator::setPeerArch(std::string_view arch)
{
    if (arch.empty() || !isValidText(arch, kMaxArchLength, isValidArchChar))
    {
        CLOG(ERROR) << "Invalid peer architecture (size:" << arch.size() << ")";
        return false;
    }

    peer_arch_ = arch;
    return true;
}

//--------------------------------------------------------------------------------------------------
bool Authenticator::setPeerDisplayName(std::string_view display_name)
{
    // Unlike the other fields, the display name is optional and may be empty.
    if (!isValidText(display_name, kMaxDisplayNameLength, isPrintableChar))
    {
        CLOG(ERROR) << "Invalid peer display name (size:" << display_name.size() << ")";
        return false;
    }

    peer_display_name_ = display_name;
    return true;
}
